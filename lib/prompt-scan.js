/**
 * Prompt disclosure.
 *
 * Several plugins append text to the system prompt (or to the per-step runtime
 * context) that only explains how to use their *own* tools — `dsh-free-search`
 * lists its engines, `dsh-image-gen` describes provider defaults, `dsh-mcp-client`
 * prints each server's instructions. Once those tools live behind a gateway, that
 * prose describes tools the model cannot see, and it is re-read on every request
 * even in sessions that never touch the family.
 *
 * This module removes that prose from the prefix and hands it back at the moment
 * it becomes useful: the family's `action: "list"` result.
 *
 * **Where the text is cut.** Not by rewriting the assembly — a runtime context is
 * re-resolved from its *registered provider* by `systemPrompt.refreshContext()`
 * on every step (dsh-agent-loop calls it to admit the runtime-context message), so
 * blanking the assembled copy would be undone before the request is built. The
 * registrations themselves are wrapped instead: the entry's `text` provider is
 * replaced by one that returns `""` and keeps the real text. Both code paths then
 * agree, and the value is stable from the very first assembly of a session.
 *
 * Two properties matter and both are deliberate:
 *
 *  1. **The prefix never changes.** Text is blanked from the first assembly on, so
 *     the rendered prompt is byte-identical on every turn.
 *  2. **Nothing is lost.** The resolved text is captured on the way out and
 *     re-emitted by `dispatch.js` when the family is listed.
 *
 * Attribution is the hard part: `systemPrompt.section()` runs during another
 * plugin's `apply`, and most of those plugins mount before this one (it is the
 * last bundle in the profile). Three layers, in order:
 *
 *  L1 — live: wrap the `systemPrompt` service instance's `section`/`context` so a
 *       registration made after this plugin mounted records its registrant, and
 *       so the entry's provider is wrapped as it is created.
 *  L2 — static: `PROMPT_ATTRIBUTION`, generated by
 *       `scripts/gen-prompt-attribution.mjs` from the installed trees.
 *  L3 — name: `mcp:<server>` belongs to the MCP server family regardless of who
 *       registered it.
 *
 * Anything still unattributed is left injected. That is the safe direction: a
 * missing disclosure costs context, never correctness.
 */

import { callerPackageOf, isHarnessPackage } from "./ownership-channel.js";
import { PROMPT_ATTRIBUTION } from "./prompt-attribution.js";

/**
 * Sections/contexts that must never be blanked even if a rule matches.
 *
 * This is the fallback for host sections whose names we know. A plugin can now
 * say so itself by registering with `mutable: false` — see `isImmutable` — and
 * that declaration wins, because a hard-coded list of names can only ever cover
 * the registrations that existed when it was written.
 */
const NEVER_BLANK = new Set([
  "harness:identity",
  "deployment:persona-prefix",
  "deployment:persona-suffix",
  "approval:policy",
  "sandbox:policy",
  "working-directory:current",
  "team:identity",
]);

/** Names this plugin owns; blanking them would remove our own notice. */
const OWN_PREFIX = "tool-gate:";

/**
 * Which single reason describes a package's row.
 *
 * Ordered by what the user can act on: if anything is disclosable the row is
 * `ready`; otherwise the first reason that a settings change would fix wins,
 * and only then the ones that describe a plugin which simply has nothing to
 * disclose.
 */
const REASON_PRIORITY = [
  "ready",
  "no-switch",
  "master-off",
  "requires-collapse",
  "required-only",
  "no-family",
  "unowned",
  "no-prose",
];

function pickReason(reasons, available) {
  if (available) return "ready";
  for (const candidate of REASON_PRIORITY) {
    if (reasons.includes(candidate)) return candidate;
  }
  return "no-prose";
}

/** Marks a provider this module already wrapped, so re-install cannot stack layers. */
const WRAPPED = Symbol.for("dsh-tool-gate.prompt-provider");

/** Look one registration up in the generated table (exact, then longest prefix). */
function lookupStatic(name) {
  const exact = PROMPT_ATTRIBUTION[name];
  if (exact !== undefined) return exact;
  let best;
  let bestLength = -1;
  for (const key of Object.keys(PROMPT_ATTRIBUTION)) {
    if (!PROMPT_ATTRIBUTION[key].prefix) continue;
    const prefix = key.slice(0, -1);
    if (name.startsWith(prefix) && prefix.length > bestLength) {
      best = PROMPT_ATTRIBUTION[key];
      bestLength = prefix.length;
    }
  }
  return best;
}

/** Every prompt layer currently registered: the global one plus any scoped ones. */
function layerList(service) {
  const layers = service?.layers;
  if (layers === undefined) return [];
  const out = [];
  if (layers.global !== undefined) out.push(layers.global);
  for (const layer of layers.scoped?.values?.() ?? []) out.push(layer);
  return out;
}

/**
 * Build the disclosure engine.
 *
 * @param options.ctx - plugin context (for live attribution).
 * @param options.logger - optional logger.
 * @param options.config - live config reader.
 * @param options.families - live resolved family table.
 * @param options.isCollapsedFamily - `(familyId) => boolean` for this session.
 * @returns the engine handle.
 */
export function createPromptDisclosure(options) {
  const { ctx, logger, config, families, isCollapsedFamily } = options;

  /** name -> package, learned live (wins over the generated snapshot). */
  const learned = new Map();
  /** name -> { name, kind, text, family }: the most recent text withheld per entry. */
  const withheld = new Map();
  /** Entries whose provider this module replaced, for restore-on-dispose. */
  const adopted = [];

  /** The `systemPrompt` service, or undefined before it exists. */
  const promptService = () => {
    try {
      return ctx.get("systemPrompt", false);
    } catch {
      return undefined;
    }
  };

  /** Package that registered one prompt entry, or undefined when unknown. */
  const packageOf = (name) => {
    if (typeof name !== "string" || name === "") return undefined;
    if (name.startsWith("mcp:")) {
      return learned.get(name) ?? lookupStatic(name)?.package ?? "@deepseek-ai/dsh-mcp-client";
    }
    return learned.get(name) ?? lookupStatic(name)?.package;
  };

  /** Whether this entry is `required` (never blanked) per the static table. */
  const isRequired = (name) => lookupStatic(name)?.required === true;

  /** Family a package's prompt text belongs to (by family ownership of the package). */
  const familyOfPackage = (pkg) => {
    if (typeof pkg !== "string" || pkg === "") return undefined;
    for (const family of Object.values(families())) {
      if ((family.packages ?? []).includes(pkg)) return family.id;
    }
    return undefined;
  };

  /** Family a prompt entry belongs to, using the package then the name shape. */
  const familyOfEntry = (name) => {
    if (typeof name !== "string") return undefined;
    if (name.startsWith("mcp:")) return "mcp_servers";
    return familyOfPackage(packageOf(name));
  };

  /**
   * Whether an entry forbids its own disclosure.
   *
   * A plugin registering a section can pass `mutable: false` to say "this is
   * required context; do not withhold it". The host does not interpret the
   * field — it stores the registration object as given — so this is a
   * convention between us and the registering plugin, which is still the right
   * way round: the plugin that knows a section is load-bearing declares it,
   * instead of us guessing from its name.
   *
   * Read from the live registration on every call, so a plugin that flips
   * `mutable` after registering is honoured without a remount.
   *
   * @param name - prompt section or context name.
   * @returns whether the entry is immutable.
   */
  const isImmutable = (name) => {
    if (typeof name !== "string") return false;
    if (NEVER_BLANK.has(name)) return true;
    for (const layer of layerList(promptService())) {
      if (layer.sections?.get?.(name)?.mutable === false) return true;
      if (layer.contexts?.get?.(name)?.mutable === false) return true;
    }
    return false;
  };

  /** Whether this specific entry may be blanked right now. */
  const shouldBlank = (name) => {
    const live = config();
    if (live.promptDisclosure !== true) return false;
    if (typeof name !== "string" || name === "") return false;
    if (name.startsWith(OWN_PREFIX)) return false;
    if (isImmutable(name)) return false;
    if (isRequired(name)) return false;
    const pkg = packageOf(name);
    if (pkg === undefined) return false;
    const plugins = live.promptPlugins ?? {};
    const row = plugins[pkg];
    if (row === undefined || row === null || row.enabled !== true) return false;
    const family = familyOfEntry(name);
    // Only disclosure for a family that is actually collapsed in this session:
    // otherwise its tools are on the wire and its prose is still accurate.
    if (family === undefined || !isCollapsedFamily(family)) return false;
    return true;
  };

  /**
   * Replace one entry's `text` provider with a withholding wrapper.
   *
   * The wrapper resolves the original provider — string or function — and returns
   * `""` while the entry is disclosable, remembering what it dropped. Because it
   * sits on the *registration*, it applies to `assemble()` and `refreshContext()`
   * alike, which is what makes the runtime-context message lose the prose too.
   *
   * @param entry - the registered prompt section or context.
   * @param kind - `"section"` or `"context"`.
   */
  const adopt = (entry, kind) => {
    if (entry === null || typeof entry !== "object") return entry;
    const name = entry.name;
    if (typeof name !== "string" || name === "") return entry;
    // A `complete` section replaces the whole prompt for its scope; blanking it
    // would erase that scope's system prompt rather than one contribution.
    if (entry.complete === true) return entry;
    const original = entry.text;
    if (typeof original !== "string" && typeof original !== "function") return entry;
    if (original[WRAPPED] === true) return entry;
    const wrapper = function withholdingText(context) {
      if (!shouldBlank(name)) return typeof original === "function" ? original(context) : original;
      let text;
      try {
        text = typeof original === "function" ? original(context) : original;
      } catch (error) {
        // A provider that throws must keep throwing to its owner; blanking is not
        // a licence to swallow another plugin's bug.
        throw error;
      }
      if (typeof text === "string" && text !== "") {
        withheld.set(name, { name, kind, text, family: familyOfEntry(name) });
      }
      return "";
    };
    wrapper[WRAPPED] = true;
    wrapper.original = original;
    adopted.push({ entry, original });
    entry.text = wrapper;
    return entry;
  };

  /** Wrap every entry already registered (they were registered before this mount). */
  const adoptRegistered = () => {
    const service = promptService();
    for (const layer of layerList(service)) {
      for (const [name, entry] of layer.sections?.entries?.() ?? []) {
        adopt(entry ?? { name, text: undefined }, "section");
      }
      for (const [name, entry] of layer.contexts?.entries?.() ?? []) {
        adopt(entry ?? { name, text: undefined }, "context");
      }
    }
  };

  // ——— live attribution + adoption ————————————————————————————————
  // `internal/get` fires when a context first resolves a service, so wrapping that
  // instance's methods observes every later registration together with the caller.
  const patched = new WeakSet();
  const restores = [];

  const wrapService = (service) => {
    if (service === null || typeof service !== "object" || patched.has(service)) return service;
    patched.add(service);
    for (const method of ["section", "context"]) {
      const original = service[method];
      if (typeof original !== "function") continue;
      const kind = method === "section" ? "section" : "context";
      const wrapper = function registered(entry) {
        const name = entry?.name;
        if (typeof name === "string" && name !== "") {
          // The caller's package, read from the carrier context — see
          // `ownership-channel.js`. This used to read `ctx.fiber.name`, which is
          // *this plugin's* fiber and therefore never the registrant, so every
          // live attribution silently failed.
          const owner = callerPackageOf(this);
          if (owner !== undefined) learned.set(name, owner);
        }
        adopt(entry, kind);
        return original.call(this, entry);
      };
      wrapper.attributedOriginal = original;
      service[method] = wrapper;
      restores.push(() => {
        // Restore unconditionally: `service` is a traceable proxy, so reading
        // `service[method]` hands back a fresh proxy and an identity check
        // against `wrapper` can never pass — the wrapper would stay installed
        // and the next mount would stack a second one on top of it.
        try {
          service[method] = original;
        } catch {
          /* the service is gone; nothing to restore */
        }
      });
    }
    return service;
  };

  const disposeListener = ctx.on("internal/get", (carrier, property, _error, next) => {
    if (property !== "systemPrompt") return next();
    return wrapService(next());
  });

  try {
    const live = ctx.get("systemPrompt", false);
    if (live !== undefined) wrapService(live);
  } catch {
    /* the listener above covers later resolutions */
  }
  // An `internal/get` wrapper only sees services resolved *through* this context
  // after it mounts; the ones already registered need adopting directly.
  adoptRegistered();

  /**
   * Measure the currently registered prompt contributions.
   *
   * Text providers are functions of the assembly context; calling them without a
   * scope is the best available approximation ("how big is this when it applies"),
   * and a provider that refuses simply reports 0. Only used for the settings page.
   *
   * @returns Map<name, { kind, chars, package }>
   */
  const measure = () => {
    const out = new Map();
    for (const layer of layerList(promptService())) {
      for (const [name, entry] of layer.sections?.entries?.() ?? []) {
        if (out.has(name)) continue;
        let text = "";
        try {
          const provider = entry?.text?.[WRAPPED] === true ? entry.text.original : entry?.text;
          text = typeof provider === "function" ? String(provider({}) ?? "") : String(provider ?? "");
        } catch {
          text = "";
        }
        out.set(name, { kind: "section", chars: text.length, package: packageOf(name) });
      }
      for (const [name, entry] of layer.contexts?.entries?.() ?? []) {
        if (out.has(name)) continue;
        let text = "";
        try {
          const provider = entry?.text?.[WRAPPED] === true ? entry.text.original : entry?.text;
          text = typeof provider === "function" ? String(provider({}) ?? "") : String(provider ?? "");
        } catch {
          text = "";
        }
        out.set(name, { kind: "context", chars: text.length, package: packageOf(name) });
      }
    }
    return out;
  };

  /**
   * The withheld prose, grouped by family, for one agent's `list` to return.
   *
   * Reads what the wrapped providers actually dropped, so the returned text is
   * exactly what the model would have seen in the prefix.
   *
   * @returns `{ [familyId]: [{ name, kind, text }] }`
   */
  const collect = () => {
    const out = {};
    for (const row of withheld.values()) {
      if (row.family === undefined) continue;
      if (!isCollapsedFamily(row.family)) continue;
      (out[row.family] ??= []).push({ name: row.name, kind: row.kind, text: row.text });
    }
    for (const rows of Object.values(out)) {
      rows.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
    }
    return out;
  };

  /**
   * Why one prompt entry is or is not disclosable right now.
   *
   * The page needs this to be honest: "greyed out" without a reason is
   * indistinguishable from a bug, and the ways to be undisclosable have
   * completely different fixes (switch the family on / nothing to disclose /
   * the text is required context).
   *
   * @param name - prompt section or context name.
   * @returns one of `ready`, `no-switch`, `master-off`, `requires-collapse`,
   *   `required-only`, `no-family`, `unowned`.
   */
  const reasonFor = (name) => {
    const live = config();
    const pkg = packageOf(name);
    if (pkg === undefined) return "unowned";
    const family = familyOfEntry(name);
    if (family === undefined) return "no-family";
    if (isRequired(name) || isImmutable(name)) return "required-only";
    if (live.promptDisclosure !== true) return "master-off";
    const row = live.promptPlugins?.[pkg];
    if (row === undefined || row === null || row.enabled !== true) return "no-switch";
    if (!isCollapsedFamily(family)) return "requires-collapse";
    return "ready";
  };

  return {
    adopt,
    collect,
    shouldBlank,
    reasonFor,
    isImmutable,
    packageOf,
    familyOfEntry,
    measure,
    /**
     * Everything currently attributable, for the settings page.
     *
     * `disclosureAvailable` is the decision the engine would make right now;
     * `family` is the family whose gateway would carry the prose. A row without a
     * family (or whose family is not collapsed) is listed but cannot be switched
     * on — the page greys it out instead of pretending it does something.
     */
    inventory() {
      const rows = new Map();
      const sizes = measure();
      const add = (name) => {
        const pkg = packageOf(name);
        if (pkg === undefined) return;
        const size = sizes.has(name) ? sizes.get(name) : undefined;
        const family = familyOfEntry(name);
        const row = rows.get(pkg) ?? {
          package: pkg,
          family,
          names: [],
          required: false,
          chars: 0,
          disclosureAvailable: false,
          reasons: [],
          hasText: false,
        };
        if (!row.names.includes(name)) row.names.push(name);
        if (isRequired(name)) row.required = true;
        if (row.family === undefined && family !== undefined) row.family = family;
        const chars = size?.chars ?? 0;
        row.chars += chars;
        if (chars > 0) row.hasText = true;
        const reason = reasonFor(name);
        if (!row.reasons.includes(reason)) row.reasons.push(reason);
        if (family !== undefined && isCollapsedFamily(family) && !isRequired(name) && !isImmutable(name)) {
          row.disclosureAvailable = true;
        }
        rows.set(pkg, row);
      };
      for (const name of Object.keys(PROMPT_ATTRIBUTION)) {
        if (PROMPT_ATTRIBUTION[name].prefix) continue;
        add(name);
      }
      for (const name of sizes.keys()) add(name);
      for (const name of learned.keys()) add(name);
      // The most actionable reason describes the row as a whole: a plugin with
      // one disclosable entry and one required entry is still disclosable.
      for (const row of rows.values()) {
        row.reason = pickReason(row.reasons, row.disclosureAvailable);
      }
      return [...rows.values()].sort((a, b) => (a.package < b.package ? -1 : a.package > b.package ? 1 : 0));
    },
    dispose() {
      disposeListener?.();
      for (const restore of restores.splice(0)) {
        try {
          restore();
        } catch {
          /* already restored */
        }
      }
      for (const { entry, original } of adopted.splice(0)) {
        if (entry?.text?.[WRAPPED] === true) entry.text = original;
      }
      withheld.clear();
    },
  };
}
