import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Which installed plugin registers which tool — read from the packages themselves.
 *
 * Ownership of a tool can be learned live (see `owner.js`): every registration that
 * happens *after* this plugin mounts is caught by the `register` wrapper. That
 * covers anything installed later, at any scope.
 *
 * It does not cover the tools that already existed when this plugin mounted. Those
 * registrations are over, and the registry keeps no ownership metadata, so nothing
 * observes them. The previous answer was a checked-in snapshot of the profile's
 * registry, regenerated by hand — which meant installing a plugin left its tools
 * exposed until someone re-ran a script.
 *
 * This module removes that step. When an unplaced tool name shows up, it reads the
 * profile's own bundles and asks them directly: a tool is registered by the package
 * whose source contains `name: "<that tool>"`. The mapping is therefore derived
 * from what is installed, not from a list in this repository.
 *
 * Only the profile's bundle list is scanned, and only for names that are actually
 * unplaced, so the cost is bounded by the number of plugins the user has.
 */

/** Our own package root, used to locate the profile when the env var is absent. */
const SELF_DIR = (() => {
  try {
    return path.dirname(path.dirname(fileURLToPath(import.meta.url)));
  } catch {
    return undefined;
  }
})();

/** Our own package name, so the scan can never attribute a tool to this plugin. */
const SELF_PACKAGE_NAME = (() => {
  try {
    const manifest = JSON.parse(fs.readFileSync(path.join(SELF_DIR, "package.json"), "utf8"));
    return typeof manifest.name === "string" ? manifest.name : undefined;
  } catch {
    return undefined;
  }
})();

/** A registration's name, in any of the three literal forms a package may use. */
const NAME_IN_SOURCE = /name\s*:\s*["'`]([A-Za-z_][A-Za-z0-9_.-]*)["'`]/g;

/** A registration's name when it points at a constant instead of a literal. */
const NAME_IDENTIFIER = /name\s*:\s*([A-Za-z_$][A-Za-z0-9_$]*)\s*[,}]/g;

/** A `const X = "literal"` declaration, which is how a bundle names its tools. */
const CONST_LITERAL = /(?:const|let|var)\s+([A-Za-z_$][A-Za-z0-9_$]*)\s*=\s*["'`]([A-Za-z_][A-Za-z0-9_.-]*)["'`]/g;

/** `export const X = 'literal'` appears as a plain declaration; both forms match above. */

/** Directories never worth walking: dependencies, VCS, build output. */
const SKIP_DIRS = new Set(["node_modules", ".git", "dist", "build", ".cache", "coverage"]);

/** Extensions worth reading; source maps and declarations are noise. */
const READABLE = /\.(?:js|mjs|cjs|jsx|ts|mts|cts)$/;

/** Ignore a single file larger than this — bundles that big are not worth the read. */
const MAX_FILE_BYTES = 12 * 1024 * 1024;

/** Per-profile cache: the bundle list and file list change only on install. */
const cache = new Map();

/** Read one JSON file, or undefined. */
function readJson(file) {
  try {
    return JSON.parse(fs.readFileSync(file, "utf8"));
  } catch {
    return undefined;
  }
}

/**
 * Locate the active profile directory.
 *
 * `DSH_PROFILE_DIR` is the authoritative answer — the host sets it. The fallback
 * walks up from this package looking for a manifest that declares
 * `dsh.profile.bundles`, which is what makes a directory a profile.
 */
export function profileDir() {
  const declared = process.env.DSH_PROFILE_DIR;
  if (typeof declared === "string" && declared !== "") {
    if (fs.existsSync(path.join(declared, "package.json"))) return declared;
  }
  let dir = SELF_DIR;
  for (let depth = 0; depth < 6 && dir !== undefined; depth += 1) {
    const manifest = readJson(path.join(dir, "package.json"));
    if (Array.isArray(manifest?.dsh?.profile?.bundles)) return dir;
    const parent = path.dirname(dir);
    dir = parent === dir ? undefined : parent;
  }
  return undefined;
}

/** Resolve one bundle specifier to its directory under the profile. */
function bundleDir(root, specifier) {
  if (typeof specifier !== "string" || specifier === "") return undefined;
  const direct = path.join(root, "node_modules", specifier);
  if (fs.existsSync(path.join(direct, "package.json"))) return direct;
  // A bundle can also be the profile's own local directory (e.g. "./plugins/x").
  const local = path.resolve(root, specifier);
  if (fs.existsSync(path.join(local, "package.json"))) return local;
  return undefined;
}

/** Collect readable source files under a package, breadth-first and bounded. */
function sourceFiles(root) {
  const files = [];
  const queue = [root];
  while (queue.length > 0) {
    const dir = queue.pop();
    let entries;
    try {
      entries = fs.readdirSync(dir, { withFileTypes: true });
    } catch {
      continue;
    }
    for (const entry of entries) {
      if (entry.name.startsWith(".") || SKIP_DIRS.has(entry.name)) continue;
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) queue.push(full);
      else if (entry.isFile() && READABLE.test(entry.name)) files.push(full);
    }
  }
  return files;
}

/**
 * Ask the installed bundles which of `wanted` they register.
 *
 * @param wanted - tool names still lacking an owner.
 * @param logger - plugin logger for one summary line.
 * @param root - profile directory to scan; defaults to {@link profileDir}.
 * @returns `{ [toolName]: packageName }` for every name a package claimed.
 */
export function scanForOwners(wanted, logger, root = profileDir()) {
  const found = {};
  if (!(wanted instanceof Set) || wanted.size === 0) return found;
  if (root === undefined) return found;

  let plan = cache.get(root);
  if (plan === undefined) {
    const manifest = readJson(path.join(root, "package.json"));
    const bundles = Array.isArray(manifest?.dsh?.profile?.bundles) ? manifest.dsh.profile.bundles : [];
    const packages = [];
    for (const specifier of bundles) {
      const dir = bundleDir(root, specifier);
      if (dir === undefined) continue;
      const pkg = readJson(path.join(dir, "package.json"));
      if (typeof pkg?.name !== "string" || pkg.name === "") continue;
      // Never attribute to ourselves: our own tests and docs mention tool names,
      // and claiming them would hand us families that belong to other plugins.
      if (pkg.name === SELF_PACKAGE_NAME) continue;
      packages.push({ name: pkg.name, files: sourceFiles(dir) });
    }
    plan = { packages };
    cache.set(root, plan);
    logger?.debug?.(`dsh-tool-gate: tool scan indexed ${packages.length} installed bundle(s)`);
  }

  for (const pkg of plan.packages) {
    for (const file of pkg.files) {
      let stat;
      try {
        stat = fs.statSync(file);
      } catch {
        continue;
      }
      if (stat.size === 0 || stat.size > MAX_FILE_BYTES) continue;
      let source;
      try {
        source = fs.readFileSync(file, "utf8");
      } catch {
        continue;
      }
      // Cheap rejection first: a file that does not mention any wanted name cannot
      // claim one, and that is most files in most bundles.
      let relevant = false;
      for (const name of wanted) {
        if (found[name] === undefined && source.includes(name)) {
          relevant = true;
          break;
        }
      }
      if (!relevant) continue;

      const remaining = () => {
        for (const name of wanted) if (found[name] === undefined) return true;
        return false;
      };

      // Literal form: `name: "tool_name"`.
      NAME_IN_SOURCE.lastIndex = 0;
      let match;
      while (remaining() && (match = NAME_IN_SOURCE.exec(source)) !== null) {
        const name = match[1];
        if (wanted.has(name) && found[name] === undefined) found[name] = pkg.name;
      }
      if (!remaining()) continue;

      // Constant form: `name: PROBE_TOOL_NAME` resolved through
      // `export const PROBE_TOOL_NAME = 'video_probe'` — how dsh-video-storyboard
      // and others spell their tool names.
      const constants = new Map();
      CONST_LITERAL.lastIndex = 0;
      while ((match = CONST_LITERAL.exec(source)) !== null) constants.set(match[1], match[2]);
      if (constants.size === 0) continue;
      NAME_IDENTIFIER.lastIndex = 0;
      while (remaining() && (match = NAME_IDENTIFIER.exec(source)) !== null) {
        const resolved = constants.get(match[1]);
        if (resolved === undefined) continue;
        if (wanted.has(resolved) && found[resolved] === undefined) found[resolved] = pkg.name;
      }
    }
  }

  const claimed = Object.keys(found).length;
  if (claimed > 0) {
    logger?.debug?.(`dsh-tool-gate: tool scan placed ${claimed} pre-existing tool(s)`);
  }
  return found;
}

/** Drop the cached index (used by tests; the host never needs it). */
export function forgetScanCache() {
  cache.clear();
}

export default { scanForOwners, profileDir, forgetScanCache };
